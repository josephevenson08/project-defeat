#!/usr/bin/env node
/**
 * Writes CHANGELOG.md: what was worked on, day by day, straight from `git log`.
 *
 * Usage:  npm run changelog
 *
 * **Generated rather than kept by hand, for the reason everything else in this repo is.** A hand-kept
 * log is out of date by the next commit, and the owner reads this on GitHub to see what happened on a
 * given day. `HANDOFF.md` is the narrative — why things were done and what was learned — and it is
 * long by design; this is the index into it, one line per commit.
 *
 * **Commits that change nothing but CHANGELOG.md are left out**, and that is what makes the file able
 * to be current at all. Without it the commit that refreshes the log would always be missing from it,
 * so a second run would always find something new and the file would never settle. With it, a refresh
 * commit is invisible and a second run writes nothing — the same idempotency `npm run brain` keeps,
 * which matters because the repo lives in OneDrive and every rewrite is a sync.
 *
 * **Days are the committer's calendar days**, read with `--date=short` in each commit's own recorded
 * timezone. Converting to UTC would move an evening's work in Missouri onto the next day, which is not
 * when it happened.
 *
 * `--full-history` keeps side-branch commits a path filter could otherwise prune; merges are dropped
 * because the commits they bring in are listed individually and most merge subjects are only a branch
 * name. Nothing here reaches the network — the commit links are built from the `origin` URL.
 */

import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const OUTPUT = join(ROOT, 'CHANGELOG.md')
const OUTPUT_NAME = 'CHANGELOG.md'

const FIELD = '\x1f'
const RECORD = '\x1e'

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December']
const WEEKDAYS = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday']

function git(args) {
  return execFileSync('git', args, { cwd: ROOT, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })
}

/** `https://github.com/owner/repo` from whatever form `origin` is written in, or undefined. */
function repositoryUrl() {
  let remote
  try {
    remote = git(['remote', 'get-url', 'origin']).trim()
  } catch {
    return undefined
  }
  const match = remote.match(/github\.com[:/](.+?)(?:\.git)?$/)
  return match ? `https://github.com/${match[1]}` : undefined
}

function readCommits() {
  const raw = git([
    'log',
    '--no-merges',
    '--full-history',
    '--date=short',
    `--format=%H${FIELD}%h${FIELD}%ad${FIELD}%s${RECORD}`,
    '--',
    '.',
    `:(exclude)${OUTPUT_NAME}`,
  ])

  return raw
    .split(RECORD)
    .map((record) => record.trim())
    .filter(Boolean)
    .map((record) => {
      const [hash, short, date, subject] = record.split(FIELD)
      return { hash, short, date, subject }
    })
}

/**
 * Weekday from a calendar date. Built in UTC on purpose: the date string is already the committer's
 * local day, and parsing it as local time here could slide it by one depending on the machine.
 */
function describeDay(isoDate) {
  const [year, month, day] = isoDate.split('-').map(Number)
  const weekday = WEEKDAYS[new Date(Date.UTC(year, month - 1, day)).getUTCDay()]
  return { weekday, year, month, day }
}

/** Keeps a subject from breaking the list it sits in. Subjects here are prose, so this is rarely hit. */
function escapeMarkdown(text) {
  return text.replace(/([\\`*_[\]<>])/g, '\\$1')
}

function render(commits, repoUrl) {
  const byDay = new Map()
  for (const commit of commits) {
    if (!byDay.has(commit.date)) byDay.set(commit.date, [])
    byDay.get(commit.date).push(commit)
  }

  // `git log` is newest first already; sorting again makes the order a property of the file rather
  // than of whichever flags git was given.
  const days = [...byDay.keys()].sort().reverse()
  const first = days.at(-1)
  const last = days[0]

  const lines = [
    '# What was worked on, day by day',
    '',
    'Every day with a commit, newest first, one line per commit — straight from `git log`.',
    '',
    `**${commits.length} commits across ${days.length} days**, from ${first} to ${last}.`,
    '',
    'For *why* something was done and what it turned up, read [`HANDOFF.md`](HANDOFF.md): it is the',
    'narrative this is the index into. Each hash below links to the full commit, whose message usually',
    'explains the change in more detail than its title.',
    '',
    '> Generated by `npm run changelog` — do not edit by hand, because the next run replaces the whole',
    '> file. Commits that change only this file are left out, so refreshing it never adds a line.',
  ]

  let currentMonth
  for (const date of days) {
    const { weekday, year, month, day } = describeDay(date)
    const monthLabel = `${MONTHS[month - 1]} ${year}`

    if (monthLabel !== currentMonth) {
      currentMonth = monthLabel
      const monthCommits = days
        .filter((entry) => entry.startsWith(date.slice(0, 7)))
        .reduce((total, entry) => total + byDay.get(entry).length, 0)
      lines.push('', `## ${monthLabel}`, '', `_${monthCommits} commits_`)
    }

    const entries = byDay.get(date)
    const count = entries.length === 1 ? '1 commit' : `${entries.length} commits`
    lines.push('', `### ${weekday} ${day} ${MONTHS[month - 1]} — ${count}`, '')

    // Oldest first within a day, so a day reads in the order the work happened.
    for (const commit of [...entries].reverse()) {
      const reference = repoUrl ? `[\`${commit.short}\`](${repoUrl}/commit/${commit.hash})` : `\`${commit.short}\``
      lines.push(`- ${escapeMarkdown(commit.subject)} — ${reference}`)
    }
  }

  return `${lines.join('\n')}\n`
}

const commits = readCommits()
if (commits.length === 0) {
  console.error('changelog: git log returned no commits — is this being run inside the repository?')
  process.exit(1)
}

const next = render(commits, repositoryUrl())
const previous = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8').replace(/\r\n/g, '\n') : undefined

if (previous === next) {
  console.log(`changelog: ${OUTPUT_NAME} unchanged (${commits.length} commits)`)
} else {
  writeFileSync(OUTPUT, next, 'utf8')
  console.log(`changelog: ${OUTPUT_NAME} written (${commits.length} commits)`)
}
