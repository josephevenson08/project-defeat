// Maps every gathered material name to its Wowhead icon name, for the profession pages.
//
// **Why a second icon mapping rather than a row in the first.** `ingest-icons.mjs` maps the *item
// catalogue* — gear, gems, raid loot — keyed by item id, because that is what the paperdoll renders.
// Trade goods are not in the catalogue and never will be: nobody equips Peacebloom. So the join here
// is by **name**, which is what the profession data actually holds, and it reads the same
// MIT-licensed wowsims CSV at the same pinned commit so the two mappings cannot describe different
// item sets.
//
// **Only the structured `materials` field is read, never the display label.** `material` is written
// for a person ("Thorium Ore (incl. Rich Thorium Vein at 275+)") and parsing it back into a key is
// precisely the mistake that cost this repo 28 of its 43 route maps — see `MaterialFarmSpot`.
//
// Crafting `keyMaterials` are deliberately out of scope: they are still prose ("15 Golden Sansam,
// Dreamfoil or Mountain Silversage — whichever matches the craft you picked"), and splitting a
// quantity off the front of a sentence is the same error in a new place. They get icons when they
// get structure.
//
// Run: node tools/ingest/ingest-material-icons.mjs
// Writes: src/domain/professions/materialIcons.json

import { mkdirSync, existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { registerHooks } from 'node:module'
import { fileURLToPath, pathToFileURL } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const REPO = resolve(HERE, '../..')

registerHooks({
  resolve(specifier, context, nextResolve) {
    try {
      return nextResolve(specifier, context)
    } catch (err) {
      if (!specifier.startsWith('.')) throw err
      try {
        return nextResolve(`${specifier}.ts`, context)
      } catch {
        return nextResolve(`${specifier}/index.ts`, context)
      }
    }
  },
})

/** Same commit as the item catalogue and the icon mapping, so all three describe one item set. */
const UPSTREAM_SHA = '3301fca59306a747e521274c36e073e69acc7b77'
const UPSTREAM_URL = `https://raw.githubusercontent.com/wowsims/tbc/${UPSTREAM_SHA}/assets/item_data/all_item_tooltips.csv`
const CACHE_PATH = resolve(HERE, `.cache/all_item_tooltips.${UPSTREAM_SHA.slice(0, 8)}.csv`)
const OUT_PATH = resolve(REPO, 'src/domain/professions/materialIcons.json')

async function loadUpstream() {
  mkdirSync(dirname(CACHE_PATH), { recursive: true })
  if (existsSync(CACHE_PATH)) return readFileSync(CACHE_PATH, 'utf8')
  const res = await fetch(UPSTREAM_URL)
  if (!res.ok) throw new Error(`all_item_tooltips.csv: HTTP ${res.status}`)
  const text = await res.text()
  writeFileSync(CACHE_PATH, text)
  return text
}

const csv = await loadUpstream()

/*
 * Narrow regexes over the row rather than JSON.parse of 30,000 tooltip blobs, matching how
 * `ingest-icons.mjs` reads the same file. Item names can carry an apostrophe (Khadgar's Whisker) but
 * never a double quote, which is what makes this safe.
 */
const byName = new Map()
for (const line of csv.split('\n')) {
  const comma = line.indexOf(',')
  if (comma <= 0) continue
  const id = Number(line.slice(0, comma))
  if (!Number.isInteger(id)) continue
  const name = line.match(/"name":"([^"]+)"/)?.[1]
  const icon = line.match(/"icon":"([^"]+)"/)?.[1]
  if (!name || !icon) continue
  // Lowest id wins: a duplicated name is a later re-issue of the same trade good.
  if (!byName.has(name) || byName.get(name).id > id) byName.set(name, { id, icon })
}

const { gatheringMaterialFarming } = await import(
  pathToFileURL(resolve(REPO, 'src/domain/professions/sampleGatheringMaterials.ts')).href
)

const wanted = [
  ...new Set(
    Object.values(gatheringMaterialFarming)
      .flat()
      .flatMap((spot) => spot.materials),
  ),
].sort()

const materials = {}
const missing = []
for (const name of wanted) {
  const hit = byName.get(name)
  if (hit) materials[name] = { wowItemId: hit.id, icon: hit.icon }
  else missing.push(name)
}

writeFileSync(
  OUT_PATH,
  `${JSON.stringify(
    {
      note: 'Generated by tools/ingest/ingest-material-icons.mjs. Do not edit by hand.',
      upstream: { repo: 'wowsims/tbc', sha: UPSTREAM_SHA, path: 'assets/item_data/all_item_tooltips.csv' },
      materials,
      missing,
    },
    null,
    2,
  )}\n`,
)

console.log(`${wanted.length} gathered materials -> ${Object.keys(materials).length} resolved, ${missing.length} missing`)
if (missing.length > 0) console.log(`  missing: ${missing.join(', ')}`)
console.log(`wrote ${OUT_PATH.replace(REPO, '.')}`)
