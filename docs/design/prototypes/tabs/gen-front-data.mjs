// Builds front-data.js for the front-door designs (front-a/b/c.html). Run from the repo root:
//   node docs/design/prototypes/tabs/gen-front-data.mjs
// Every count a front door states comes from src/ here, bundled with the rolldown Vite already ships (as
// gen-sim-engine.mjs does): the raids with their bosses and drops, the professions, the raid buffs the app counts,
// the specs with a ranked gear list, and the top tier of Wowhead's DPS list. Regenerate rather than hand-editing.
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const REPO = path.resolve(".");
const T = path.join(REPO, "docs/design/prototypes/tabs");
const { rolldown } = await import(pathToFileURL(path.join(REPO, "node_modules/rolldown/dist/index.mjs")).href);
const ENTRY = `
export { sampleRaids } from '../../src/domain/raids/sampleRaids'
export { sampleRaidBosses } from '../../src/domain/raids/sampleRaidBosses'
export { allProfessions, sampleProfessions } from '../../src/domain/professions/sampleProfessions'
export { modelledBuffs } from '../../src/domain/buffs/sampleBuffs'
export { bisLists } from '../../src/domain/bis/bisLists'
export { default as tierLists } from '../../src/domain/tierlists/tierLists.json' with { type: 'json' }
`;
const inside = path.join(REPO, "node_modules", ".front-data");
fs.mkdirSync(inside, { recursive: true });
fs.writeFileSync(path.join(inside, "entry.ts"), ENTRY);
const bundle = await rolldown({ input: path.join(inside, "entry.ts"), platform: "node", logLevel: "warn" });
const { output } = await bundle.generate({ format: "esm" });
await bundle.close?.();
const tmp = path.join(inside, "data.mjs");
fs.writeFileSync(tmp, output[0].code);
const D = await import(pathToFileURL(tmp).href);
fs.rmSync(inside, { recursive: true, force: true });

/* the raids in the order a Phase 2 raider meets them: this tier first */
const ORDER = ["serpentshrine-cavern", "tempest-keep", "karazhan", "gruuls-lair", "magtheridons-lair"];
const raids = ORDER.map(id => D.sampleRaids.find(r => r.id === id)).filter(Boolean).map(r => {
  const bosses = D.sampleRaidBosses.filter(b => b.raidId === r.id);
  return { id: r.id, name: r.name, phase: r.phase, bosses: bosses.length, drops: bosses.reduce((n, b) => n + (b.loot || []).length, 0),
    art: fs.existsSync(path.join(REPO, "public/raids", r.id + ".jpg")) ? `raids/${r.id}.jpg` : null };
});
const dps = D.tierLists.lists.find(l => l.role === "DPS");
const data = {
  raids,
  bosses: raids.reduce((n, r) => n + r.bosses, 0),
  drops: raids.reduce((n, r) => n + r.drops, 0),
  professions: D.allProfessions.length,
  professionIcons: D.sampleProfessions.map(p => ({ name: p.profession ?? p.name, icon: p.icon })).filter(p => p.icon),
  buffs: D.modelledBuffs.length,
  bisSpecs: D.bisLists.length,
  tierTop: { label: dps.tiers[0].label, specs: dps.tiers[0].placements.map(p => ({ className: p.className, spec: p.spec })), source: dps.sourceUrl },
  dpsSpecs: dps.tiers.reduce((n, t) => n + t.placements.length, 0),
};
fs.writeFileSync(path.join(T, "front-data.js"), `/* front-data.js — GENERATED by gen-front-data.mjs on ${new Date().toISOString().slice(0, 10)} from src/domain (do not edit by hand).
   The counts and lists the front-door designs show: raids with bosses and drops, professions, counted raid buffs, specs
   with a ranked gear list, and the top tier of Wowhead's Phase 2 DPS list. */
window.FRONT_DATA=${JSON.stringify(data)};
`);
console.log(JSON.stringify(data, null, 1).slice(0, 1200));
