// Builds tier-data.js for the Spec Tier Lists designs from the live app's own data. Run from the repo root:
//   node docs/design/prototypes/tabs/gen-tier-data.mjs
// It bundles src/domain with the rolldown Vite already ships (as gen-sim-engine.mjs does) and reads:
//   tierlists/tierLists.json (Wowhead's three Phase 2 lists), simulation/dpsReference (archon.gg's observed average DPS
//   and tier for the 20 DPS specs, from logs), raidcomp (the 29 raid builds, their spec icons, and what each brings to a
//   raid: party buffs, raid-wide buffs and boss debuffs, through the same seatContributions Raid Composition counts),
//   character (roles and class colours) and abilities (each spec's signature ability).
// Regenerate after any of those change; never hand-edit tier-data.js.
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { pathToFileURL } from "node:url";

const REPO = path.resolve(".");
const T = path.join(REPO, "docs/design/prototypes/tabs");
const { rolldown } = await import(pathToFileURL(path.join(REPO, "node_modules/rolldown/dist/index.mjs")).href);

const ENTRY = `
import { specTierLists } from '../../src/domain/tierlists'
import { dpsReference, DPS_REFERENCE_SOURCE } from '../../src/domain/simulation/dpsReference'
import { raidBuilds, seatContributions } from '../../src/domain/raidcomp'
import { getBuffIcon } from '../../src/domain/raidcomp/raidcompIcons'
import { getRoleForSpec, tbcClasses } from '../../src/domain/character/tbcClasses'
import { getClassColor } from '../../src/domain/character/classColors'
import { getSignatureAbility } from '../../src/domain/abilities/sampleSignatureAbilities'
import tierJson from '../../src/domain/tierlists/tierLists.json' with { type: 'json' }
export { specTierLists, dpsReference, DPS_REFERENCE_SOURCE, raidBuilds, seatContributions, getBuffIcon, getRoleForSpec, tbcClasses, getClassColor, getSignatureAbility, tierJson }
`;
const inside = path.join(REPO, "node_modules", ".tier-data");
fs.mkdirSync(inside, { recursive: true });
fs.writeFileSync(path.join(inside, "entry.ts"), ENTRY);
const bundle = await rolldown({ input: path.join(inside, "entry.ts"), platform: "browser", logLevel: "warn" });
const { output } = await bundle.generate({ format: "iife", name: "PDTier" });
await bundle.close?.();
fs.rmSync(inside, { recursive: true, force: true });
const box = {};
vm.runInNewContext(output[0].code + ";this.PDTier=PDTier;", box);
const X = box.PDTier;

const key = (c, s) => `${c}|${s}`;
/* every spec the app knows, in the class order the app uses */
const specs = {};
for (const def of X.tbcClasses) for (const spec of def.specs) {
  const k = key(def.className, spec);
  const builds = X.raidBuilds.filter(b => b.className === def.className && b.spec === spec);
  /* what the spec brings: coverage matches on the spec, never the build, so a bear and a cat bring the same */
  const c = X.seatContributions({ className: def.className, spec, buildId: builds[0]?.id });
  const thing = (b, scope) => ({ id: b.id, n: b.name, ic: X.getBuffIcon(b.id) || null, scope });
  const ab = X.getSignatureAbility(def.className, spec);
  const ref = X.dpsReference.find(r => r.className === def.className && r.spec === spec);
  specs[k] = {
    cls: def.className, spec, role: X.getRoleForSpec(def.className, spec), col: X.getClassColor(def.className),
    icon: builds[0]?.icon || null, builds: builds.map(b => ({ id: b.id, label: b.label, role: b.role, icon: b.icon })),
    places: [], archon: ref ? { dps: ref.dps, tier: ref.tier } : null, ability: ab ? ab.name : null,
    brings: [...c.raidWide.map(b => thing(b, "raid")), ...c.party.map(b => thing(b, "party")), ...c.debuffs.map(b => thing(b, "debuff"))],
  };
}
const lists = X.specTierLists.map(l => ({
  role: l.role, title: l.title, url: l.sourceUrl, phase: l.phase,
  tiers: l.tiers.map(t => ({ label: t.label, specs: t.placements.map(p => key(p.className, p.spec)) })),
}));
lists.forEach(l => l.tiers.forEach(t => t.specs.forEach(k => { if (!specs[k]) throw new Error("unknown spec " + k); specs[k].places.push({ role: l.role, label: t.label }); })));
/* the archon ranking: observed average DPS, highest first */
const archonOrder = X.dpsReference.slice().sort((a, b) => b.dps - a.dps).map(r => key(r.className, r.spec));
const out = {
  lists, specs, archonOrder,
  sources: { wowhead: "Wowhead, The Burning Crusade Classic Phase 2 PvE rankings (tier letters and placements only)", ingest: X.tierJson.generatedBy, archon: X.DPS_REFERENCE_SOURCE },
  counts: { lists: lists.length, placements: lists.reduce((n, l) => n + l.tiers.reduce((m, t) => m + t.specs.length, 0), 0), specs: Object.keys(specs).length, archon: X.dpsReference.length },
};
const day = new Date().toISOString().slice(0, 10);
const js = `/* tier-data.js — GENERATED by gen-tier-data.mjs on ${day} from src/domain (do not edit by hand).
   Wowhead's three Phase 2 tier lists (tierlists/), archon.gg's observed DPS and tier for the 20 DPS specs
   (simulation/dpsReference), and per spec: role, class colour, spec icon and raid builds, its signature ability, and what
   it brings to a raid (raidcomp seatContributions: raid-wide buffs, party buffs, boss debuffs). */
window.TIER_DATA=${JSON.stringify(out)};
`;
fs.writeFileSync(path.join(T, "tier-data.js"), js);
const brings = Object.values(specs).reduce((n, s) => n + s.brings.length, 0);
console.log(`tier-data.js written (${Math.round(js.length / 1024)} KB): ${out.counts.lists} lists, ${out.counts.placements} placements, ${out.counts.specs} specs, ${out.counts.archon} with archon.gg DPS, ${brings} buff/debuff links`);
