// Generates docs/design/prototypes/tabs/talent-data.js for the three Talents designs, from the app's real data:
// warriorTalents.json (Wowhead's TBC talent calculator: rows, columns, ranks, per-rank text, prerequisites, icons),
// talentBuilds.json (the wowsims Fury and Arms presets, as stored) and talentEffects.json (which talents the live
// simulator reads, and why it skips the ones it doesn't). Run from the repo root.
import fs from "node:fs";
const D = "src/domain/talents/";
const J = p => JSON.parse(fs.readFileSync(D + p, "utf8"));
const raw = J("warriorTalents.json"), builds = J("talentBuilds.json"), fx = J("talentEffects.json");

const trees = raw.trees.map(t => ({
  spec: t.spec,
  talents: t.talents.map(x => ({ id: x.id, name: x.name, icon: x.icon, row: x.row, col: x.column, max: x.maxRank,
    ranks: x.rankDescriptions, req: x.requires.map(r => [r.id, r.rank]) })).sort((a, b) => a.row - b.row || a.col - b.col),
}));
const names = new Map(trees.flatMap(t => t.talents.map(x => [x.name, x.id])));

const presets = {};
for (const b of builds.builds.filter(b => b.className === "Warrior")) {
  presets[b.spec] = { source: "wowsims/tbc " + b.source, points: Object.fromEntries(Object.entries(b.points).map(([k, v]) => [+k, v])) };
}

/* what the live simulator reads, keyed by talent id (Vitality has two entries: stamina and strength) */
const effects = {};
for (const e of fx.effects.filter(e => e.className === "Warrior")) {
  (effects[e.talentId] ||= []).push(Object.fromEntries(Object.entries({ kind: e.kind, per: e.perRank, flat: e.flatValue, stat: e.stat, caveat: e.caveat }).filter(([, v]) => v !== undefined)));
}
/* what it deliberately skips, keyed by talent id (one entry can name several talents: "Mace/Sword/Poleaxe Specialization") */
const skipped = {};
for (const s of fx.skipped.filter(s => s.className === "Warrior")) {
  for (const n of s.talent.split("/").map(p => p.trim()).map(p => /Specialization$/.test(p) ? p : /^(Mace|Sword|Poleaxe)$/.test(p) ? p + " Specialization" : p)) {
    const id = names.get(n); if (id) skipped[id] = s.reason;
  }
}

const out = { className: "Warrior", total: 61, perRow: 5, rows: 9, upstream: fx.upstream.sha, trees, presets, effects, skipped };
const js = `/* talent-data.js — GENERATED by gen-talent-data.mjs from src/domain/talents (do not edit by hand).
   Warrior talent trees from Wowhead's TBC calculator; the wowsims/tbc Fury and Arms presets as stored; which talents the
   live simulator reads (effects) and why it skips others (skipped). */
window.TALENT_DATA=${JSON.stringify(out)};
`;
fs.writeFileSync("docs/design/prototypes/tabs/talent-data.js", js);
console.log(`talent-data.js written (${Math.round(js.length / 1024)} KB): ${trees.map(t => t.spec + " " + t.talents.length).join(", ")}; presets ${Object.keys(presets).join(", ")}; ${Object.keys(effects).length} simulated, ${Object.keys(skipped).length} skipped`);
